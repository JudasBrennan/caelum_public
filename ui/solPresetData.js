function planet(id, name, inputs) {
  return { id, name, slotIndex: null, locked: false, inputs: { name, ...inputs } };
}

function moon(
  id,
  name,
  planetId,
  semiMajorAxisKm,
  eccentricity,
  inclinationDeg,
  massMoon,
  densityGcm3,
  albedo,
  compositionOverride = null,
) {
  return {
    id,
    name,
    planetId,
    locked: false,
    inputs: {
      name,
      semiMajorAxisKm,
      eccentricity,
      inclinationDeg,
      massMoon,
      densityGcm3,
      albedo,
      compositionOverride,
    },
  };
}

function comet(
  id,
  name,
  sourceReservoir,
  semiMajorAxisAu,
  eccentricity,
  inclinationDeg,
  longitudeOfPeriapsisDeg,
  meanAnomalyDeg,
  nucleusRadiusKm,
  densityGcm3,
  albedo,
  activeFraction,
  dustToGasRatio,
  volatileClass,
) {
  return {
    id,
    name,
    hostFrameId: "star_a",
    sourceReservoir,
    semiMajorAxisAu,
    eccentricity,
    inclinationDeg,
    longitudeOfPeriapsisDeg,
    meanAnomalyDeg,
    nucleusRadiusKm,
    densityGcm3,
    albedo,
    activeFraction,
    dustToGasRatio,
    volatileClass,
  };
}

